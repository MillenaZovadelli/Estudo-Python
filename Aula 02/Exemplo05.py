# Entrada de dados com  vários tipos

nome = input("Digite o seu nome: ")
sobrenome = input("Digite o seu sobrenome: ")
idade = input("Digite a sua idade: ") # lê como string
print(f"Nome completo: {nome} {sobrenome}.")
print(f"Idade: {idade} anos.") 

num1 = int(input("Digite n1: ")) # lê como inteiro
num2 = int(input("Digite n2: "))
print(num1 + num2)
print(num1 - num2)
print(num1 * num2)
print(num1 / num2)

num3 = float(input("Digite n3: ")) # lê como ponto flutuante
print(num3)
