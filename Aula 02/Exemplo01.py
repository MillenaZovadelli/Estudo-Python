# Utilização de Variáveis e Saída de Dados.
'''
Este é um Exemplo de um comentario de multiplas linhas em Python. Note que são três aspas duplas no inicio e no final do comentario.
'''
# Declara e inicializa as variáveis.
valor1 = 5; valor2 = 2

# Realiza o cálculo.
soma = valor1 + valor2

# Exibe o resultado.
print("O resultado finaç é: ", soma)
print("O resultado final é: %d" % soma)
print("O resultado final é: {}".format(soma))

# f ou F - formatted string literals
print(f"O resultado final é: {soma}")